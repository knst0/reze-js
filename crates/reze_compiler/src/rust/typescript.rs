use super::ir::{FieldDef, TypeDef, TypeRef};
use super::source::{CRATE, Project, Route};

const TYPES: &str = "virtual:reze-types/";

fn ts_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::String => "string".into(),
        TypeRef::Boolean => "boolean".into(),
        TypeRef::Number { .. } => "number".into(),
        TypeRef::Bigint { rust } => format!("import(\"reze-js/types\").{}", rust.to_uppercase()),
        TypeRef::Option { of } => format!("{} | null", ts_type(of)),
        TypeRef::List { of } if matches!(**of, TypeRef::Option { .. }) => {
            format!("({})[]", ts_type(of))
        }
        TypeRef::List { of } => format!("{}[]", ts_type(of)),
        TypeRef::Date => "Date".into(),
        TypeRef::Set { of } => format!("Set<{}>", ts_type(of)),
        TypeRef::Map { value } => format!("Map<string, {}>", ts_type(value)),
        TypeRef::Tuple { items } => {
            format!("[{}]", items.iter().map(ts_type).collect::<Vec<_>>().join(", "))
        }
        TypeRef::Defer { of } => ts_type(of),
        TypeRef::Named { name } => name.clone(),
    }
}

fn fields(fields: &[FieldDef]) -> String {
    fields.iter().map(|field| format!("; {}: {}", field.name, ts_type(&field.ty))).collect()
}

fn declaration(ty: &TypeDef) -> String {
    match ty {
        TypeDef::Struct { name, fields } => {
            let body: String = fields
                .iter()
                .map(|field| format!("  {}: {};\n", field.name, ts_type(&field.ty)))
                .collect();
            format!("export interface {name} {{\n{body}}}\n")
        }
        TypeDef::Enum { name, variants } => {
            let variants: Vec<String> = variants.iter().map(|v| format!("{v:?}")).collect();
            format!("export type {name} = {};\n", variants.join(" | "))
        }
        TypeDef::Union { name, variants } => {
            let variants: Vec<String> = variants
                .iter()
                .map(|v| format!("{{ kind: {:?}{} }}", v.name, self::fields(&v.fields)))
                .collect();
            format!("export type {name} = {};\n", variants.join(" | "))
        }
    }
}

fn result_type(output: Option<&String>) -> &str {
    output.map_or("void", String::as_str)
}

pub fn declarations(project: &Project, route: &Route) -> String {
    let mut out = format!(
        "// Generated by reze-js from {}. Do not edit.\nimport type {{ Mutation }} from \"reze-js/server\";\n\n",
        route.file
    );
    for ty in &project.ir.types {
        out.push_str(&declaration(ty));
    }
    if let Some(data) = &route.load {
        out.push_str(&format!("export type Data = {data};\n"));
    }
    for mutation in &route.mutations {
        out.push_str(&format!(
            "export declare const {}: Mutation<{}, {}>;\n",
            mutation.export,
            mutation.input,
            result_type(mutation.output.as_ref())
        ));
    }
    out
}

pub fn route_suffix(route: &Route) -> String {
    let mut out = String::from("\n");
    let mut imports = Vec::new();
    if route.load.is_some() {
        imports.push("loader as __rzLoader");
    }
    if route.has_guard {
        imports.push("guardRoute as __rzGuard");
    }
    if imports.is_empty() {
        return String::new();
    }
    out.push_str(&format!("import {{ {} }} from \"reze-js/server\";\n", imports.join(", ")));
    if let Some(data) = &route.load {
        out.push_str(&format!(
            "import type {{ {data} as __rzData }} from \"{TYPES}{CRATE}\";\nexport const load = __rzLoader.external<__rzData>();\n"
        ));
    }
    if route.has_guard {
        out.push_str("export const guard = __rzGuard.external();\n");
    }
    out
}

pub fn module(project: &Project, route: &Route) -> String {
    let mut out = String::new();
    if !route.mutations.is_empty() {
        out.push_str("import { mutation as __rzMutation } from \"reze-js/server\";\n");
    }
    let names: Vec<&str> = project.ir.types.iter().map(TypeDef::name).collect();
    if !names.is_empty() {
        let names = names.join(", ");
        out.push_str(&format!(
            "import type {{ {names} }} from \"{TYPES}{CRATE}\";\nexport type {{ {names} }};\n"
        ));
    }
    if let Some(data) = &route.load {
        out.push_str(&format!("export type Data = {data};\n"));
    }
    for mutation in &route.mutations {
        let options = match &mutation.revalidate {
            Some(patterns) => {
                let patterns: Vec<String> = patterns.iter().map(|p| format!("{p:?}")).collect();
                format!("{{ revalidate: [{}] }}", patterns.join(", "))
            }
            None => String::new(),
        };
        out.push_str(&format!(
            "export const {} = __rzMutation.external<{}, {}>({options});\n",
            mutation.export,
            mutation.input,
            result_type(mutation.output.as_ref())
        ));
    }
    out
}
